"""Phase 5 Streamlit dashboard. Run it with:

    python -m streamlit run dashboard\\app.py

### It cannot start a simulation, by construction

This file imports exactly one project module, :mod:`smartwaste.dashboard_data`, which is stdlib
only and reads two things: the committed demo snapshot in ``dashboard/demo_data/`` and the
committed ``docs/PHASE*_RESULTS.md``. There is no import of ``city_sim``, ``benchmark``,
``phase3``, ``phase4`` or anything under ``smartwaste.ml`` anywhere on this page, so no
interaction can trigger a long job -- there is nothing here to trigger.
``tests/test_dashboard_app.py`` asserts that by reading this file's source.

### Every number on this page is one of two things

**Simulated**, from the 200-bin x 14-day seeded demo snapshot -- a demonstration of the pipeline,
not a result, and never compared with the Phase 2 city benchmark. Or **copied from a results
doc**, parsed at display time so it cannot drift from the document, and always shown under that
document's own heading. Those headings carry the project's honesty labels -- ``SMOKE RUN``,
``NOT RUN``, ``fair test``, ``UPPER BOUND, NOT REALISTIC`` -- and are rendered verbatim, so a
table can never appear here without the warning that was attached to it.

Nothing on this page is a hardware reading. ``plotly`` is imported lazily inside each figure
function, so a missing ``app`` extra degrades to tables with a clear message instead of a stack
trace.
"""

from __future__ import annotations

from pathlib import Path
from types import ModuleType

import streamlit as st

from smartwaste.dashboard_data import (
    BASELINE_HEADING,
    DOCS_DIR,
    NOT_VERIFIED_HEADING,
    PAPER_REFERENCE_HEADING,
    PHASE3_NOT_RUN_HEADING,
    PHASE4_ALGORITHMS_HEADING,
    PHASE4_CAPACITY_HEADING,
    PHASE4_EXECUTION_HEADING,
    REDUCTION_HEADING,
    RESULTS_DOCS,
    SIMPLER_BASELINE_HEADING,
    SIMULATED_DATA_BANNER,
    BinDayRow,
    DemoCity,
    DocTable,
    find_tables,
    load_demo,
    load_doc_tables,
    section_text,
)

#: Colour-blind-safe-ish G/Y/R. Deliberately not the traffic-light primaries: a saturated
#: pure green and red are the hardest pair for a deuteranope, and these differ in lightness too.
STATE_COLOURS = {"GREEN": "#1b7837", "YELLOW": "#e08214", "RED": "#b2182b"}
STATE_ORDER = ("RED", "YELLOW", "GREEN")

DEMO_CAPTION = (
    "Demo snapshot: 200 bins x 14 days, seed 42. A demonstration of the pipeline, "
    "NOT the Phase 2 city benchmark (5000 bins x 30 days) and not comparable with it."
)
GRID_CAPTION = (
    "Synthetic 100 x 100 km grid. NOT a real city and NOT geographic coordinates -- "
    "bins are uniform-random points, and the axes are kilometres, not latitude and longitude."
)


@st.cache_data
def _demo() -> DemoCity:
    return load_demo()


@st.cache_data
def _doc_tables() -> tuple[DocTable, ...]:
    return load_doc_tables()


@st.cache_data
def _doc_text(name: str) -> str:
    return (DOCS_DIR / name).read_text(encoding="utf-8")


def _plotly() -> ModuleType | None:
    """Import plotly on demand. Returns ``None`` when the ``app`` extra is not installed."""
    try:
        import plotly.graph_objects as go
    except ImportError:
        return None
    # Annotated through a local: plotly ships no stubs, so `go` is Any and returning it
    # directly trips mypy's no-any-return under strict mode.
    module: ModuleType = go
    return module


def _no_plotly_notice() -> None:
    st.warning(
        "plotly is not installed, so the charts are unavailable. Install the optional extra:\n\n"
        '    python -m pip install -e ".[app]"\n\n'
        "Every table on this page still works without it."
    )


# --- panels ----------------------------------------------------------------------------------


def render_banner(city: DemoCity) -> None:
    """The banner, from ``meta.json``'s own label so the two cannot drift apart."""
    st.error(f"**{city.meta.label}**", icon="⚠️")
    st.caption(
        f"Generated by `{city.meta.command}` -- seed {city.meta.seed}, "
        f"{city.meta.n_bins} bins, {city.meta.days} days, {city.meta.n_clusters} clusters, "
        f"demand scenario `{city.meta.scenario}`, stuck-sensor fraction "
        f"{city.meta.stuck_bin_fraction}."
    )
    st.caption(f"Strategy driving collection: {city.meta.strategy_label}")


def render_map(city: DemoCity, day: int, rows: tuple[BinDayRow, ...], state_field: str) -> None:
    st.subheader(f"Bin states, day {day}")
    go = _plotly()
    if go is None:
        _no_plotly_notice()
    else:
        by_bin = {b.bin_id: b for b in city.bins}
        figure = go.Figure()
        for state in STATE_ORDER:
            picked = [r for r in rows if getattr(r, state_field) == state]
            if not picked:
                continue
            figure.add_trace(
                go.Scatter(
                    x=[by_bin[r.bin_id].x_km for r in picked],
                    y=[by_bin[r.bin_id].y_km for r in picked],
                    mode="markers",
                    name=f"{state} ({len(picked)})",
                    marker={"size": 9, "color": STATE_COLOURS[state], "line": {"width": 0}},
                    customdata=[
                        [r.bin_id, r.true_fill_pct, r.est_fill_pct, r.true_weight_kg]
                        for r in picked
                    ],
                    hovertemplate=(
                        "bin %{customdata[0]}<br>true fill %{customdata[1]:.1f}%"
                        "<br>sensor fill %{customdata[2]:.1f}%"
                        "<br>true weight %{customdata[3]:.1f} kg<extra></extra>"
                    ),
                )
            )
        figure.add_trace(
            go.Scatter(
                x=[city.meta.depot_x_km],
                y=[city.meta.depot_y_km],
                mode="markers",
                name="depot",
                marker={"size": 16, "color": "#2166ac", "symbol": "square"},
                hovertemplate="depot<extra></extra>",
            )
        )
        figure.update_layout(
            height=560,
            xaxis={"title": "km", "range": [0, city.meta.grid_km]},
            yaxis={
                "title": "km",
                "range": [0, city.meta.grid_km],
                "scaleanchor": "x",
                "scaleratio": 1,
            },
            legend={"title": "state"},
            margin={"l": 50, "r": 20, "t": 20, "b": 40},
        )
        st.plotly_chart(figure, use_container_width=True)

    st.caption(GRID_CAPTION)

    truth = {s: sum(1 for r in rows if r.true_state == s) for s in STATE_ORDER}
    sensed = {s: sum(1 for r in rows if r.sensor_state == s) for s in STATE_ORDER}
    disagree = sum(1 for r in rows if r.true_state != r.sensor_state)
    missed = sum(1 for r in rows if r.true_state == "RED" and not r.selected)

    left, right = st.columns(2)
    with left:
        st.markdown("**Ground truth vs what the sensors reported**")
        st.dataframe(
            [
                {"state": s, "ground truth": truth[s], "sensor fusion": sensed[s]}
                for s in STATE_ORDER
            ],
            hide_index=True,
            use_container_width=True,
        )
    with right:
        st.metric("bins where the two disagree", disagree)
        st.metric("RED bins not collected (missed pickups)", missed)
    st.caption(
        "The gap between the two columns is the point of the project. Ground truth is available "
        "here only because the city is simulated; on real hardware there is no such column, "
        "which is why `docs/PHASE1_RESULTS.md` measures the rule and not the outcome."
    )


def render_routes(city: DemoCity, day: int) -> None:
    st.subheader(f"Truck routes, day {day}")
    routes = city.routes_for_day(day)
    if not routes:
        st.info(
            f"No bins were selected on day {day}, so no truck rolled. "
            "Under the paper's rule a day with no RED bin is a day with no collection."
        )
        return

    go = _plotly()
    if go is None:
        _no_plotly_notice()
    else:
        figure = go.Figure()
        for cluster, points in routes.items():
            figure.add_trace(
                go.Scatter(
                    x=[p.x_km for p in points],
                    y=[p.y_km for p in points],
                    mode="lines+markers",
                    name=f"cluster {cluster}",
                    marker={"size": 7},
                    line={"width": 2},
                    hovertemplate=f"cluster {cluster}<br>stop %{{pointNumber}}<extra></extra>",
                )
            )
        figure.add_trace(
            go.Scatter(
                x=[city.meta.depot_x_km],
                y=[city.meta.depot_y_km],
                mode="markers",
                name="depot",
                marker={"size": 16, "color": "#2166ac", "symbol": "square"},
                hovertemplate="depot<extra></extra>",
            )
        )
        figure.update_layout(
            height=560,
            xaxis={"title": "km", "range": [0, city.meta.grid_km]},
            yaxis={
                "title": "km",
                "range": [0, city.meta.grid_km],
                "scaleanchor": "x",
                "scaleratio": 1,
            },
            margin={"l": 50, "r": 20, "t": 20, "b": 40},
        )
        st.plotly_chart(figure, use_container_width=True)

    st.caption(
        "One tour per cluster per day, starting and ending at the single central depot: "
        "nearest-neighbour construction then 2-opt, Euclidean distance. "
        "Straight lines, NOT roads -- Phase 4 measured a ~1.45x median road detour for one 3 km "
        "Chennai area, and `docs/ASSUMPTIONS.md` states that factor does not transfer here."
    )
    st.dataframe(
        [
            {
                "cluster": cluster,
                "stops (incl. depot)": len(points),
                "bins visited": sum(1 for p in points if not p.is_depot),
            }
            for cluster, points in routes.items()
        ],
        hide_index=True,
        use_container_width=True,
    )
    st.caption(
        f"{city.meta.n_clusters} KMeans clusters, fixed for the whole horizon and computed on "
        "bin locations only -- territories are balanced by area, not by workload."
    )


def render_kpis(city: DemoCity) -> None:
    st.subheader("KPIs across the demo horizon")
    st.caption(DEMO_CAPTION)
    kpis = city.kpi_rows()

    totals = {
        "distance km": sum(k.distance_km for k in kpis),
        "travel time hr": sum(k.travel_time_hr for k in kpis),
        "CO2 kg": sum(k.co2_kg for k in kpis),
        "variable cost (INR)": sum(k.variable_cost for k in kpis),
        "bin visits": sum(k.bins_visited for k in kpis),
        "overflow events": sum(k.overflow_events for k in kpis),
    }
    columns = st.columns(3)
    for index, (name, value) in enumerate(totals.items()):
        with columns[index % 3]:
            st.metric(name, f"{value:,.2f}" if isinstance(value, float) else f"{value:,}")
    st.caption(
        "Every cost and CO2 constant behind these figures is INVENTED AND UNCITED "
        "(`docs/ASSUMPTIONS.md`, first banner), so the absolute INR and kg carry no external "
        "meaning. Only comparisons between strategies are informative."
    )

    go = _plotly()
    if go is None:
        _no_plotly_notice()
        st.dataframe([vars(k) for k in kpis], hide_index=True, use_container_width=True)
        return

    series = (
        ("distance_km", "distance, km", "#2166ac"),
        ("travel_time_hr", "travel time, hr", "#762a83"),
        ("co2_kg", "CO2, kg", "#1b7837"),
        ("variable_cost", "variable cost, INR", "#b35806"),
    )
    days = [k.day for k in kpis]
    for field, title, colour in series:
        figure = go.Figure(
            go.Bar(x=days, y=[getattr(k, field) for k in kpis], marker={"color": colour})
        )
        figure.update_layout(
            height=220,
            title={"text": title, "font": {"size": 14}},
            xaxis={"title": "day", "dtick": 1},
            yaxis={"title": ""},
            margin={"l": 60, "r": 20, "t": 40, "b": 35},
        )
        st.plotly_chart(figure, use_container_width=True)

    figure = go.Figure(
        go.Scatter(
            x=days,
            y=[k.bins_visited for k in kpis],
            mode="lines+markers",
            name="bins visited",
            line={"color": "#2166ac"},
        )
    )
    figure.add_trace(
        go.Bar(
            x=days,
            y=[k.overflow_events for k in kpis],
            name="overflow events",
            marker={"color": "#b2182b"},
        )
    )
    figure.update_layout(
        height=260,
        title={"text": "bins visited, and overflow events", "font": {"size": 14}},
        xaxis={"title": "day", "dtick": 1},
        margin={"l": 60, "r": 20, "t": 40, "b": 35},
    )
    st.plotly_chart(figure, use_container_width=True)
    st.caption(
        "An overflow event is a transition into overflow, not a day spent there. Overflow is "
        "modelled, not physically simulated: nothing spills, and no penalty cost is attached."
    )


def _render_doc_table(table: DocTable) -> None:
    """Render one parsed table under its own verbatim heading.

    The heading is the honesty label. Rewriting it into a friendlier caption is exactly how a
    `SMOKE RUN` or `NOT RUN` warning would get lost, so it is printed as written.
    """
    st.markdown(f"**{table.heading}**")
    st.dataframe(table.as_dicts(), hide_index=True, use_container_width=True)
    st.caption(f"Source, verbatim: `docs/{table.source_doc}` -- label as written in that document.")


def render_baselines(tables: tuple[DocTable, ...]) -> None:
    st.subheader("Baseline comparison (from the committed results docs)")
    st.info(
        "These are **not** computed on this page and not from the demo snapshot. They are parsed "
        "out of `docs/PHASE*_RESULTS.md` when the page loads, so no number here can drift away "
        "from the document that reported it.",
        icon="📄",
    )

    st.markdown("### Phase 2: all five strategies, at all three stuck-sensor fractions")
    st.caption(
        "All three fault fractions are shown deliberately. `docs/ASSUMPTIONS.md` records that "
        "the (d)-mean-vs-(e)-median verdict REVERSES between 0 and 0.02, and since the fault "
        "rate is an invented number, showing one of them would let a reader pick the conclusion."
    )
    for table in find_tables(tables, BASELINE_HEADING):
        _render_doc_table(table)

    st.markdown("### Phase 2: reduction against (a) the paper's naive baseline")
    for table in find_tables(tables, REDUCTION_HEADING):
        _render_doc_table(table)

    st.markdown("### Where a simpler baseline matches or beats the paper's method")
    st.warning(
        "Strategy (b) -- collect every bin every 3 days, no sensors at all -- had **zero** "
        "overflow events and came within a few percent of the paper's sensor fusion on cost. "
        "CLAUDE.md requires that be stated plainly rather than buried, so it is here.",
        icon="⚠️",
    )
    for table in find_tables(tables, SIMPLER_BASELINE_HEADING):
        _render_doc_table(table)

    st.markdown("### Reference only: the paper's own reported percentages")
    st.caption(
        "Reference, not a target. No constant in this project was tuned toward these figures, "
        "and our reductions came out substantially larger -- mostly an artefact of a naive "
        "baseline on a uniform-random 100 km grid."
    )
    for table in find_tables(tables, PAPER_REFERENCE_HEADING):
        _render_doc_table(table)

    st.markdown("### Phase 3: the city-scale strategy benchmark was NOT RUN")
    st.error(
        "Phase 3 settles nothing about collection outcomes. The full sweep measures about 2.3 "
        "hours and was not run, so there is **no** overflow, distance or cost figure for the "
        "forecast-driven strategy and no verdict in either direction.",
        icon="🚫",
    )
    for table in find_tables(tables, PHASE3_NOT_RUN_HEADING):
        _render_doc_table(table)

    st.markdown("### Phase 4: routing, capacity and execution -- all SMOKE RUNS")
    st.error(
        "Every Phase 4 table below is a `--quick` smoke run (5 clusters / 46 bins / 1 s solver "
        "budget). The mechanism and the direction of each finding are established; **no "
        "city-scale magnitude is.** OR-Tools beat the hand-written 2-opt by 0.29%, against a "
        "2.0% threshold declared before any run -- plain 2-opt over nearest neighbour is worth "
        "twenty times more.",
        icon="🚫",
    )
    for heading in (
        PHASE4_ALGORITHMS_HEADING,
        PHASE4_CAPACITY_HEADING,
        PHASE4_EXECUTION_HEADING,
    ):
        for table in find_tables(tables, heading):
            _render_doc_table(table)


def render_limitations() -> None:
    st.subheader("Not verified / limitations")
    st.caption(
        "Rendered straight out of each results doc's own `NOT VERIFIED` section, rather than "
        "restated here where it could drift. Only 1 physical bin was ever built, every "
        "city-scale number is simulation, and all data is synthetic."
    )
    for name in RESULTS_DOCS:
        with st.expander(f"docs/{name} -- {NOT_VERIFIED_HEADING}"):
            st.markdown(section_text(_doc_text(name), NOT_VERIFIED_HEADING))


# --- page ------------------------------------------------------------------------------------


def main() -> None:
    st.set_page_config(page_title="Smart waste: IoT + AI + routing", layout="wide")
    city = _demo()
    tables = _doc_tables()

    st.title("Smart waste collection -- sensor fusion, forecasting, routing")
    render_banner(city)

    with st.sidebar:
        st.error(SIMULATED_DATA_BANNER, icon="⚠️")
        st.markdown(
            "Every figure on this page is **simulated** or **copied from a committed results "
            "doc**. No reading came from hardware. The NodeMCU firmware in this repo has never "
            "been compiled and never been flashed."
        )
        st.divider()
        day = st.slider("Day", min_value=0, max_value=city.meta.days - 1, value=7)
        colour_by = st.radio(
            "Colour bins by",
            options=("ground truth", "sensor fusion"),
            index=0,
            help=(
                "Ground truth exists only because the city is simulated. A real deployment sees "
                "the sensor column only."
            ),
        )
        st.divider()
        st.caption(f"Demo data: `dashboard/demo_data/` ({Path(city.meta.command).name} output)")

    state_field = "true_state" if colour_by == "ground truth" else "sensor_state"
    rows = city.states_for_day(day)

    map_tab, route_tab, kpi_tab, baseline_tab, limits_tab = st.tabs(
        ["Bin map", "Routes", "KPIs", "Baseline comparison", "Not verified"]
    )
    with map_tab:
        render_map(city, day, rows, state_field)
    with route_tab:
        render_routes(city, day)
    with kpi_tab:
        render_kpis(city)
    with baseline_tab:
        render_baselines(tables)
    with limits_tab:
        render_limitations()


main()
